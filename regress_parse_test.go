// ---- 1. stray END TABLE: a file must fail to open, not crash the server ----
//
// A ") ENGINE=InnoDB" line with no open CREATE TABLE used to index Tables[-1]
// and panic. The user-visible contract: the open is refused with a diagnostic
// naming the cause ("not inside CREATE TABLE").
func TestStrayEndTableRefused(t *testing.T) {
	cases := map[string]string{
		"lone end with comment": ") ENGINE=InnoDB COMMENT='x';",
		"double end after close": "-- Generated by erd-creator\n" +
			"CREATE TABLE `a` (\n  `id` INT\n) ENGINE=InnoDB;\n) ENGINE=InnoDB;\n",
		"end before any table": "-- Generated by erd-creator\n) ENGINE=InnoDB;\n" +
			"CREATE TABLE `a` (\n  `id` INT\n) ENGINE=InnoDB;\n",
	}
	for name, sql := range cases {
		func() {
			defer func() {
				if r := recover(); r != nil {
					t.Errorf("%s: panicked: %v", name, r)
				}
			}()
			_, _, err := parseMysql(sql, DialectMysql)
			if err == nil {
				t.Errorf("%s: expected error, got none", name)
				return
			}
			if !strings.Contains(err.Error(), "not inside CREATE TABLE") {
				t.Errorf("%s: error %q does not name the cause", name, err)
			}
		}()
	}
}

