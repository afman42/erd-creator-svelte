// ---- 7. size cap: files over 8 MiB are refused with 413, not loaded ----

func TestSizeCapOpenAndCopy(t *testing.T) {
	dir := t.TempDir()
	h := handleFiles(dir)

	// seed a small real file for the copy source
	rec := do(t, h, "PUT", "/api/files/small.sql", jsonBody(sampleSchema()))
	if rec.Code != 204 {
		t.Fatalf("seed: %d %s", rec.Code, rec.Body)
	}
	// grow it past the cap on disk (the stat check must fire before any read)
	big := append([]byte(mustGenSQL(sampleSchema())), make([]byte, maxOpenFile)...)
	if err := os.WriteFile(filepath.Join(dir, "small.sql"), big, 0o644); err != nil {
		t.Fatal(err)
	}

	rec = do(t, h, "GET", "/api/files/small.sql", nil)
	if rec.Code != http.StatusRequestEntityTooLarge {
		t.Errorf("open oversized: %d, want 413", rec.Code)
	}

	rec = do(t, h, "POST", "/api/files/copy", jsonBody(map[string]string{"from": "small.sql", "to": "big-copy.sql"}))
	if rec.Code != http.StatusRequestEntityTooLarge {
		t.Errorf("copy oversized: %d, want 413", rec.Code)
	}
	if _, err := os.Stat(filepath.Join(dir, "big-copy.sql")); err == nil {
		t.Error("oversized copy left a file behind")
	}
}

// ---- 8. unknown trailing referential action is reported, not defaulted ----

func TestUnknownReferentialActionReported(t *testing.T) {
	// user-visible: importing a dump with a misspelled action keeps CASCADE
	// but tells the user the file said something unrecognized
	var loss importLoss
	del, upd := impActions("ON DELETE CASCDE", &loss)
	if del != "CASCADE" {
		t.Errorf("ON DELETE default changed: %q", del)
	}
	if upd != "" {
		t.Errorf("ON UPDATE should stay omitted: %q", upd)
	}
	if len(loss.result()) == 0 {
		t.Error("misspelled action silently defaulted with no loss recorded")
	} else if !strings.Contains(strings.Join(loss.result(), "\n"), "unrecognized") {
		t.Errorf("loss does not say unrecognized: %v", loss.result())
	}

	// end to end through the import: the schema loads AND the warning rides along
	s, warnings, err := ParseImport("CREATE TABLE a (\n  id INT,\n  pid INT REFERENCES p(id) ON DELETE CASCDE\n);\nCREATE TABLE p (\n  id INT PRIMARY KEY\n);\n")
	if err != nil {
		t.Fatalf("import: %v", err)
	}
	_ = s
	found := false
	for _, w := range warnings {
		if strings.Contains(w, "unrecognized") {
			found = true
		}
	}
	if !found {
		t.Errorf("import warnings missing the action loss: %v", warnings)
	}
}

// ---- 9. impNoise word boundary: a table named BEGINNER must not vanish ----

func TestImpNoiseWordBoundary(t *testing.T) {
	if impNoise("BEGINNER") {
		t.Error("BEGINNER treated as noise")
	}
	if impNoise("COMMITTED") {
		t.Error("COMMITTED treated as noise")
	}
	// the real directives are still skipped
	for _, line := range []string{"BEGIN", "BEGIN;", "COMMIT", "COMMIT;"} {
		if !impNoise(line) {
			t.Errorf("%q should be noise", line)
		}
	}
	// user-visible: a dump creating BEGINNER opens with that table present
	s, _, err := ParseImport("CREATE TABLE BEGINNER (\n  id INT PRIMARY KEY\n);\n")
	if err != nil {
		t.Fatalf("import: %v", err)
	}
	if len(s.Tables) != 1 || s.Tables[0].Name != "BEGINNER" {
		t.Errorf("BEGINNER table lost on import: %+v", s.Tables)
	}
}

