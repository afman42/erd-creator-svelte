// ---- 2. ghost PK/UX/single-IX: a clause naming a column that does not exist
// must be refused, not silently dropped (the PK/index would vanish with no
// diagnostic). One case per clause kind per dialect. ----

func ghostDDL(dialect, clause string) string {
	switch dialect {
	case DialectPostgres:
		head := "-- Generated by erd-creator (PostgreSQL)\n"
		switch clause {
		case "pk":
			return head + "CREATE TABLE \"a\" (\n  \"id\" INT,\n  PRIMARY KEY (\"ghost\")\n);\n"
		case "ix":
			return head + "CREATE TABLE \"a\" (\n  \"id\" INT\n);\nCREATE INDEX \"ix\" ON \"a\" (\"ghost\");\n"
		}
	case DialectSqlite:
		head := "-- Generated by erd-creator (SQLite)\n"
		switch clause {
		case "pk":
			return head + "CREATE TABLE `a` (\n  `id` INT,\n  PRIMARY KEY (`ghost`)\n);\n"
		case "ix":
			return head + "CREATE TABLE `a` (\n  `id` INT\n);\nCREATE INDEX IF NOT EXISTS `ix` ON `a` (`ghost`);\n"
		}
	default: // mysql + mariadb share the grammar
		head := "-- Generated by erd-creator\n"
		if dialect == DialectMariaDB {
			head = "-- Generated by erd-creator (MariaDB)\n"
		}
		switch clause {
		case "pk":
			return head + "CREATE TABLE `a` (\n  `id` INT,\n  PRIMARY KEY (`ghost`)\n) ENGINE=InnoDB;\n"
		case "ux":
			return head + "CREATE TABLE `a` (\n  `id` INT,\n  UNIQUE KEY `ux` (`ghost`)\n) ENGINE=InnoDB;\n"
		case "ix":
			return head + "CREATE TABLE `a` (\n  `id` INT,\n  KEY `ix` (`ghost`)\n) ENGINE=InnoDB;\n"
		}
	}
	return ""
}

func TestGhostPKUXIXRejectedAllDialects(t *testing.T) {
	// which clause kinds each dialect's grammar expresses: postgres/sqlite
	// render single-column uniqueness as a column flag, so only pk/ix apply
	clauses := map[string][]string{
		DialectMysql:    {"pk", "ux", "ix"},
		DialectMariaDB:  {"pk", "ux", "ix"},
		DialectPostgres: {"pk", "ix"},
		DialectSqlite:   {"pk", "ix"},
	}
	for dialect, kinds := range clauses {
		for _, kind := range kinds {
			sql := ghostDDL(dialect, kind)
			if sql == "" {
				t.Fatalf("%s/%s: no fixture", dialect, kind)
			}
			_, err := ParseDDL(sql)
			if err == nil {
				t.Errorf("%s %s on ghost column: accepted, want rejection", dialect, kind)
				continue
			}
			if !strings.Contains(err.Error(), "unknown column") {
				t.Errorf("%s %s: error %q does not say unknown column", dialect, kind, err)
			}
		}
	}
}

// ---- 3. dangling FK: the relationship is dropped from the model but reported
// on the open response, so the user learns why an edge is missing. ----

func TestDanglingFKWarnsStrictOpen(t *testing.T) {
	sql := "CREATE TABLE `a` (\n  `id` INT,\n" +
		"  CONSTRAINT `fk_a_id` FOREIGN KEY (`id`) REFERENCES `gone` (`id`) ON DELETE CASCADE\n) ENGINE=InnoDB;\n"
	s, warnings, err := ParseDDLWithWarnings(sql)
	if err != nil {
		t.Fatalf("strict open must load, got: %v", err)
	}
	if s.Tables[0].Columns[0].Ref != nil {
		t.Error("dangling ref must be dropped from the model")
	}
	if len(warnings) == 0 {
		t.Fatal("dangling FK dropped with no warning")
	}
	found := false
	for _, w := range warnings {
		if strings.Contains(w, "gone") || strings.Contains(w, "unknown table") {
			found = true
		}
	}
	if !found {
		t.Errorf("warning does not name the missing parent: %v", warnings)
	}
}

func TestDanglingFKWarnsImportOpen(t *testing.T) {
	// foreign-shaped DDL takes the lenient path; the drop must still be reported
	sql := "CREATE TABLE a (\n  id INT,\n  CONSTRAINT fk FOREIGN KEY (id) REFERENCES gone (id) ON DELETE CASCADE\n);\n"
	s, warnings, err := ParseImport(sql)
	if err != nil {
		t.Fatalf("import must load, got: %v", err)
	}
	if s.Tables[0].Columns[0].Ref != nil {
		t.Error("dangling ref must be dropped from the model")
	}
	if len(warnings) == 0 {
		t.Fatal("import dropped the FK with no warning")
	}
}

// The open-file HTTP path surfaces the warning alongside the schema.
func TestDanglingFKWarningReachesOpenResponse(t *testing.T) {
	dir := t.TempDir()
	sql := "CREATE TABLE `a` (\n  `id` INT,\n" +
		"  CONSTRAINT `fk_a_id` FOREIGN KEY (`id`) REFERENCES `gone` (`id`) ON DELETE CASCADE\n) ENGINE=InnoDB;\n"
	if err := os.WriteFile(filepath.Join(dir, "dangle.sql"), []byte(sql), 0o644); err != nil {
		t.Fatal(err)
	}
	rec := do(t, handleFiles(dir), "GET", "/api/files/dangle.sql", nil)
	if rec.Code != 200 {
		t.Fatalf("open: %d %s", rec.Code, rec.Body)
	}
	if !strings.Contains(rec.Body.String(), `"warnings"`) {
		t.Errorf("open response carries no warnings: %s", rec.Body)
	}
}

// ---- 4. GenInserts fail-closed ----
//
// GenInsertsFor runs every value through validateOutput and returns the error
// instead of unchecked text. The gate is reachable only by a value that passes
// input validation yet trips the output scan — with the current allowlists no
// such value exists (identifiers reject `;`/controls up front), so the honest
// pin is: every representable column still emits, and the gate function itself
// rejects a hostile line. If a future type/default slips past Validate, this
// documents where it must be caught.
func TestGenInsertsFailClosedGate(t *testing.T) {
	s := &Schema{Tables: []Table{{ID: "t1", Name: "t", Columns: []Col{
		{Name: "id", Type: "INT", Pk: true},
		{Name: "note", Type: "VARCHAR(10)"},
	}}}}
	out, err := s.GenInserts()
	if err != nil {
		t.Fatalf("valid schema must emit inserts: %v", err)
	}
	if !strings.Contains(out, "INSERT INTO `t`") {
		t.Errorf("inserts missing table:\n%s", out)
	}
	// the gate the inserts path shares with DDL trips on an escaped value
	if err := validateOutput("INSERT INTO `t` (`a`) VALUES ('x'); DROP TABLE t; --\n"); err == nil {
		t.Error("validateOutput accepted an embedded separator the inserts path relies on it to catch")
	}
}

// ---- 5. type-arg comment + unbalanced paren: rejected by Validate early ----

func TestTypeArgCommentRejectedEarly(t *testing.T) {
	s := &Schema{Tables: []Table{{ID: "t1", Name: "t", Columns: []Col{
		{Name: "a", Type: "VARCHAR(1--2)"},
	}}}}
	if err := s.Validate(); err == nil {
		t.Fatal("VARCHAR(1--2) accepted by Validate")
	}
	// "early" means the field validator, not the last-gate output scan: the
	// error names the type, and GenSQL refuses too rather than emitting.
	if _, err := s.GenSQL(); err == nil {
		t.Error("GenSQL emitted a type Validate rejects")
	}
}

func TestUnbalancedParenTypeRejected(t *testing.T) {
	for _, ty := range []string{"X((", "VARCHAR(10", "INT)"} {
		s := &Schema{Tables: []Table{{ID: "t1", Name: "t", Columns: []Col{
			{Name: "a", Type: ty},
		}}}}
		if err := s.Validate(); err == nil {
			t.Errorf("type %q accepted by Validate", ty)
		}
		if _, err := s.GenSQL(); err == nil {
			t.Errorf("GenSQL emitted unbalanced type %q", ty)
		}
	}
}

