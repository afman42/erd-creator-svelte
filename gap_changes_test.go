func TestHasClausePrefixTable(t *testing.T) {
	trues := []string{
		"PRIMARY KEY (`id`)",
		"UNIQUE KEY `ux` (`a`)",
		"CONSTRAINT `fk` FOREIGN KEY (`a`) REFERENCES `t` (`id`)",
		"KEY `idx` (`a`)",
		"INDEX `idx` (`a`)",
		"FOREIGN KEY (`x`) REFERENCES `y` (`id`)",
		"primary key (`id`)",
		"key `idx` (`a`)",
		"constraint `fk` foreign key (`a`) references `t` (`id`)",
		"KEY",
		"PRIMARY KEY",
		"INDEX",
		"KEY\t`idx` (`a`)",
	}
	for _, s := range trues {
		if !hasClausePrefix(s) {
			t.Errorf("hasClausePrefix(%q) = false, want true", s)
		}
	}
	falses := []string{
		"",
		"`id` INT NOT NULL",
		"name TEXT",
		"PRIMARY",
		"PRIMARY KEYSTONE (`a`)",
		"KEYSTONE (`a`)",
		"INDEXED (`a`)",
		"CONSTRAINTX (`a`)",
		"FOREIGN KEYSTONE (`a`)",
		"UNIQUE KEYX (`a`)",
		"KEY(`a`)",
		"PRIMARY KEY(`id`)",
		"INDEX(`a`)",
		"CONSTRAINT(`fk`)",
	}
	for _, s := range falses {
		if hasClausePrefix(s) {
			t.Errorf("hasClausePrefix(%q) = true, want false", s)
		}
	}
}

func TestEmptyBodyMysqlLine(t *testing.T) {
	tbl := &Table{ID: "t1", Name: "a"}
	var pending []pendingFK
	if err := parseMysqlBodyLine("", "", tbl, &pending, 1); err == nil {
		t.Error("empty body should error, not panic or append")
	}
	if len(tbl.Columns) != 0 {
		t.Errorf("empty body appended %d columns", len(tbl.Columns))
	}
	if _, err := ParseDDL("-- Generated by erd-creator\nCREATE TABLE `a` (\n,\n) ENGINE=InnoDB;\n"); err == nil {
		t.Error("mysql stray-comma body line should reject the file")
	}
}

