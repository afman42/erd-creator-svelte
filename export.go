// export.go — server-side dialect generator (MySQL, MariaDB, PostgreSQL, SQLite).
// Dialect grammar work lives here, not in the browser: the client POSTs its schema
// JSON and gets dialect DDL back. Saved files stay MySQL-canonical; other dialects
// are export-only, which keeps the client parser a single trivial grammar.
package main

import (
	"encoding/json"
	"errors"
	"fmt"
	"net/http"
	"strings"
)

func handleExport(w http.ResponseWriter, r *http.Request) {
	b, ok := decodeBody(w, r)
	if !ok {
		return
	}
	// Dialect + schema in one pass; the schema half shares its accepted
	// envelope with every other schema endpoint via schemaEnvelope.
	var req struct {
		Dialect string `json:"dialect"`
		schemaEnvelope
	}
	if err := json.Unmarshal(b, &req); err != nil {
		http.Error(w, "bad json: "+err.Error(), http.StatusBadRequest)
		return
	}
	// Untrusted input becomes SQL text here, so it is validated before any
	// emitter sees it. A type is emitted as raw text (the type grammar is
	// open-ended), so an unvalidated one is SQL injection in the pasted output.
	//
	// Validated against the REQUESTED dialect, not the schema's own: this path
	// takes the dialect as a separate field, so a schema stored as postgres can
	// be exported as mysql, and a postgres-only construct (an array type) must
	// be refused for that target rather than emitted as invalid MySQL.
	if err := req.schema().ValidateFor(req.Dialect); err != nil {
		http.Error(w, "invalid schema: "+err.Error(), http.StatusBadRequest)
		return
	}
	sql, err := schemaExportSQL(req.schema(), req.Dialect)
	if err != nil {
		http.Error(w, err.Error(), http.StatusBadRequest)
		return
	}
	if err := validateOutput(sql); err != nil {
		http.Error(w, "invalid schema: "+err.Error(), http.StatusBadRequest)
		return
	}
	w.Header().Set("Content-Type", "text/plain; charset=utf-8")
	writeText(w, sql)
}

func exportSQL(dialect string, tables []Table) (string, error) {
	return exportSQLWith(dialect, tables, SqliteTypesNative)
}

// emitNormalized is the shared dialect dispatch for both save (GenSQL) and
// export. It uses the canonical dialect name so the two paths cannot drift.
// mysqlHeader is the header comment for the MySQL branch, which differs between
// save ("-- Generated by erd-creator") and export ("-- Generated by erd-creator (MySQL)").
func emitNormalized(normalized string, tables []Table, sqliteTypes, mysqlHeader string) string {
	switch normalized {
	case DialectPostgres:
		return buildPostgres(tables)
	case DialectMariaDB:
		return buildMariaDB(tables)
	case DialectSqlite:
		return buildSqlite(tables, sqliteTypes)
	default:
		return buildMysql(tables, mysqlHeader)
	}
}

// exportSQLWith is exportSQL with the SQLite type-rendering mode made explicit.
// Callers holding a Schema should prefer schemaExportSQL, which reads the mode
// off the schema instead of defaulting it.
func exportSQLWith(dialect string, tables []Table, sqliteTypes string) (string, error) {
	if len(tables) == 0 {
		return "", errors.New("schema has no tables")
	}
	key := strings.ToLower(strings.TrimSpace(dialect))
	if _, ok := dialectAliases[key]; !ok {
		// strict for the /export API: unknown names are rejected rather than
		// silently treated as mysql (GenSQL normalizes them, export does not).
		return "", fmt.Errorf("unknown dialect %q (want mysql, mariadb, postgres, sqlite)", dialect)
	}
	return emitNormalized(normalizeDialect(dialect), tables, sqliteTypes, "-- Generated by erd-creator (MySQL)"), nil
}

// schemaExportSQL is the export path for a schema that carries its own dialect
// and SQLite type mode, which is what /export and the UI use. Keeping it next to
// exportSQL is deliberate: the two must stay one implementation, since a second
// emitter is exactly how the save/export drift happened before.
func schemaExportSQL(s *Schema, dialect string) (string, error) {
	return exportSQLWith(dialect, s.Tables, s.sqliteTypesMode())
}

// ---- helpers ----

func quoteTick(n string) string { return "`" + strings.ReplaceAll(n, "`", "``") + "`" }
func quoteDQ(n string) string   { return `"` + strings.ReplaceAll(n, `"`, `""`) + `"` }
func sqlStr(s string) string    { return "'" + strings.ReplaceAll(s, "'", "''") + "'" }

func splitType(ty string) (string, string) {
	if i := strings.Index(ty, "("); i >= 0 && strings.HasSuffix(ty, ")") {
		return strings.ToUpper(ty[:i]), ty[i+1 : len(ty)-1]
	}
	return strings.ToUpper(ty), ""
}

// splitTop splits on top-level commas, respecting parens and quoted strings.
// All three quote characters the emitters use are honoured: single quotes
// ('...' with ” escaping), double quotes ("..." with "" escaping) and
// backticks (`...` with “ escaping). Without the backtick/double-quote cases,
// an index column or PK named `a, b` split on its comma, turning one column
// into two (and a single-column index into a composite).
func splitTop(s string) []string {
	var out []string
	depth, inStr, q, start := 0, false, byte(0), 0
	for i := 0; i < len(s); i++ {
		c := s[i]
		if inStr {
			if c == q && i+1 < len(s) && s[i+1] == q {
				i++ // skip the doubled-escape of the active quote
				continue
			}
			if c == q {
				inStr = false
			}
			continue
		}
		switch {
		case c == '\'' || c == '"' || c == '`':
			inStr = true
			q = c
		case c == '(':
			depth++
		case c == ')':
			depth--
		case c == ',' && depth == 0:
			out = append(out, strings.TrimSpace(s[start:i]))
			start = i + 1
		}
	}
	if rest := strings.TrimSpace(s[start:]); rest != "" {
		out = append(out, rest)
	}
	return out
}

func enumValues(ty string) []string {
	base, args := splitType(ty)
	if base != "ENUM" {
		return nil
	}
	var vals []string
	for _, v := range splitTop(args) {
		if len(v) >= 2 && strings.HasPrefix(v, "'") && strings.HasSuffix(v, "'") {
			v = strings.ReplaceAll(v[1:len(v)-1], "''", "'")
		}
		vals = append(vals, v)
	}
	return vals
}

// enumCheck renders an ENUM as a CHECK constraint, for dialects without a
// native enum type: CHECK (<col> IN ('a', 'b')). ok=false when ty is not an
// ENUM with at least one value, leaving the caller to fall back to TEXT.
// q quotes the column identifier (backticks or double quotes, per dialect).
func enumCheck(colName, ty string, q func(string) string) (string, bool) {
	vals := enumValues(ty)
	if vals == nil {
		return "", false
	}
	quoted := make([]string, len(vals))
	for i, v := range vals {
		quoted[i] = sqlStr(v)
	}
	return fmt.Sprintf("CHECK (%s IN (%s))", q(colName), strings.Join(quoted, ", ")), true
}

func baseOf(ty string) string {
	base, _ := splitType(ty)
	return base
}

func isInt(base string) bool {
	switch base {
	case "INT", "BIGINT", "SMALLINT", "TINYINT":
		return true
	}
	return false
}

func tableMap(tables []Table) map[string]*Table {
	m := make(map[string]*Table, len(tables))
	for i := range tables {
		m[tables[i].ID] = &tables[i]
	}
	return m
}

// pkCol: the sole PK column. ok=false for a composite PK (a single-col FK onto
// it is invalid DDL) AND for a table with no PK at all — pointing an FK at a
// non-unique first column would emit invalid MySQL, so callers skip it. Lint
// reports both cases; save (GenSQL) and export (buildMysql) now agree via this.
func pkCol(t Table) (Col, bool) {
	var pk Col
	n := 0
	for _, c := range t.Columns {
		if c.Pk {
			n++
			pk = c
		}
	}
	if n == 1 {
		return pk, true
	}
	return Col{}, false
}

// fkTargetMap resolves a column's FK to its parent table and the single PK
// column that FK references. ok=false when the parent is missing (dangling
// ref) or has no sole PK — a single-column FK onto a composite or absent PK is
// invalid DDL, so every dialect omits it. Lint reports both cases.
//
// Shared by all three dialect builders: they differ in how they render the
// constraint, not in which FKs are emittable. The map form is used because the
// build functions already carry a tableMap for Lint/FK work; the old slice
// variant (findTable/fkTarget) did an O(n) scan per FK and was removed.
func fkTargetMap(m map[string]*Table, c Col) (*Table, Col, bool) {
	if c.Ref == nil {
		return nil, Col{}, false
	}
	rt := m[c.Ref.TableID]
	if rt == nil {
		return nil, Col{}, false
	}
	rp, ok := pkCol(*rt)
	if !ok {
		return nil, Col{}, false
	}
	return rt, rp, true
}

func refCols(t Table) []Col {
	var out []Col
	for _, c := range t.Columns {
		if c.Ref != nil {
			out = append(out, c)
		}
	}
	return out
}

func fkAction(c Col) string {
	if c.Ref.Action == "" {
		return "CASCADE"
	}
	return c.Ref.Action
}

// fkUpdateClause renders the ON UPDATE clause, or "" when no action is set.
//
// Empty means omit — see the Ref comment for why ON UPDATE and ON DELETE use
// opposite conventions. Returning "" rather than a default is what keeps a
// schema without an ON UPDATE action byte-identical to the files this tool
// wrote before the field existed.
func fkUpdateClause(c Col) string {
	if c.Ref.OnUpdate == "" {
		return ""
	}
	return " ON UPDATE " + c.Ref.OnUpdate
}

func pkLine(t Table, q func(string) string) string {
	var pks []string
	for _, c := range pkCols(t) {
		pks = append(pks, q(c.Name))
	}
	if len(pks) == 0 {
		return ""
	}
	return "  PRIMARY KEY (" + strings.Join(pks, ", ") + ")"
}

// indexName returns an index's name, deriving one when unset. The derived form
// matches the single-column convention the emitters already use
// (idx_<table>_<col>), so a composite index on (a, b) becomes idx_<table>_a_b
// and needs no naming UI for the common case.
func indexName(t Table, ix Index) string {
	if ix.Name != "" {
		return ix.Name
	}
	return "idx_" + t.Name + "_" + strings.Join(ix.Cols, "_")
}

// quotedCols quotes an index's column list for the given dialect.
func quotedCols(ix Index, q func(string) string) string {
	out := make([]string, len(ix.Cols))
	for i, c := range ix.Cols {
		out[i] = q(c)
	}
	return strings.Join(out, ", ")
}

// ---- MySQL / MariaDB ----

func mysqlColDef(c Col) string {
	base, args := splitType(c.Type)
	ty := base
	// Render the argument list only when the type takes one, except for an
	// auto-increment integer: MySQL writes that as a bare AUTO_INCREMENT and
	// rejects INT(11) spelled alongside it.
	if args != "" && (!c.Ai || !isInt(base)) {
		ty = base + "(" + args + ")"
	}
	s := quoteTick(c.Name) + " " + ty
	if c.Nn || c.Pk {
		s += " NOT NULL"
	}
	if c.Ai && isInt(base) {
		s += " AUTO_INCREMENT"
	}
	if c.Ux {
		s += " UNIQUE"
	}
	if c.Comment != "" {
		s += " COMMENT " + sqlStr(c.Comment)
	}
	return s
}

func buildMysql(tables []Table, header string) string {
	byID := tableMap(tables)
	out := []string{header}
	for _, t := range tables {
		if len(t.Columns) == 0 {
			continue // empty table → invalid DDL (UI guards; parse can't produce)
		}
		var lines []string
		for _, c := range t.Columns {
			lines = append(lines, "  "+mysqlColDef(c))
		}
		if l := pkLine(t, quoteTick); l != "" {
			lines = append(lines, l)
		}
		for _, c := range t.Columns {
			if c.Ix {
				lines = append(lines, "  KEY "+quoteTick("idx_"+t.Name+"_"+c.Name)+" ("+quoteTick(c.Name)+")")
			}
		}
		// Composite indexes follow the single-column ones, in model order.
		for _, ix := range t.Indexes {
			lines = append(lines, "  KEY "+quoteTick(indexName(t, ix))+" ("+quotedCols(ix, quoteTick)+")")
		}
		for _, c := range refCols(t) {
			rt, rp, ok := fkTargetMap(byID, c)
			if !ok {
				continue
			}
			lines = append(lines, fmt.Sprintf(
				"  CONSTRAINT %s FOREIGN KEY (%s) REFERENCES %s (%s) ON DELETE %s%s",
				quoteTick("fk_"+t.Name+"_"+c.Name), quoteTick(c.Name), quoteTick(rt.Name), quoteTick(rp.Name), fkAction(c), fkUpdateClause(c)))
		}
		out = append(out, "CREATE TABLE "+quoteTick(t.Name)+" (\n"+strings.Join(lines, ",\n")+"\n) ENGINE=InnoDB;")
	}
	return strings.Join(out, "\n") + "\n"
}

// buildMariaDB emits MariaDB DDL.
//
// Today this is byte-identical to buildMysql apart from the header, because the
// two grammars have not diverged for any construct we emit. It exists as a
// separate function on purpose: it is the place MariaDB-specific syntax goes
// when it is needed, without a flag threading through the MySQL path.
//
// Delegates to buildMysql to keep the two in sync. TestMariaDBMatchesMysql pins
// them to identical bodies so the moment they diverge — deliberately or by
// accident — it fails and forces a decision. If MariaDB genuinely needs different
// DDL, replace this delegation with a divergent implementation and update that test.
func buildMariaDB(tables []Table) string {
	return buildMysql(tables, "-- Generated by erd-creator (MariaDB)")
}

// ---- PostgreSQL ----

func pgType(c Col) (string, string) { // type + inline extra (CHECK for ENUM)
	// The array suffix is split off before the base is mapped and re-attached
	// after, so `JSON[]` becomes `JSONB[]` rather than `JSONB` with the suffix
	// lost. splitType cannot do this: it uppercases and splits on "(", and
	// `INT[]` has neither.
	array := ""
	ty := c.Type
	if isArrayType(ty) {
		array = "[]"
		ty = strings.TrimSuffix(strings.TrimSpace(ty), "[]")
	}
	base, args := splitType(ty)
	switch base {
	case "TINYINT":
		base = "SMALLINT"
	case "DATETIME":
		base = "TIMESTAMP"
	case "JSON":
		base = "JSONB"
	case "ENUM":
		// ENUM[] is refused by validation, so it cannot reach here; the CHECK
		// form below is only correct for a scalar column.
		if check, ok := enumCheck(c.Name, c.Type, quoteDQ); ok {
			return "TEXT" + array, check
		}
		base = "TEXT"
	}
	if args != "" && base != "TEXT" {
		return base + "(" + args + ")" + array, ""
	}
	return base + array, ""
}

func postgresColDef(c Col) string {
	ty, extra := pgType(c)
	if c.Ai && isInt(ty) {
		ty += " GENERATED BY DEFAULT AS IDENTITY"
	}
	s := quoteDQ(c.Name) + " " + ty
	if c.Nn || c.Pk {
		s += " NOT NULL"
	}
	if c.Ux {
		s += " UNIQUE"
	}
	if extra != "" {
		s += " " + extra
	}
	return s
}

func buildPostgres(tables []Table) string {
	byID := tableMap(tables)
	out := []string{"-- Generated by erd-creator (PostgreSQL)"}
	for _, t := range tables {
		if len(t.Columns) == 0 {
			continue
		}
		var lines, post []string
		for _, c := range t.Columns {
			lines = append(lines, "  "+postgresColDef(c))
			if c.Comment != "" {
				post = append(post, fmt.Sprintf("COMMENT ON COLUMN %s.%s IS %s;",
					quoteDQ(t.Name), quoteDQ(c.Name), sqlStr(c.Comment)))
			}
			if c.Ix {
				post = append(post, fmt.Sprintf("CREATE INDEX %s ON %s (%s);",
					quoteDQ("idx_"+t.Name+"_"+c.Name), quoteDQ(t.Name), quoteDQ(c.Name)))
			}
		}
		// Composite indexes are separate statements after the table, like the
		// single-column ones above — Postgres has no inline KEY clause.
		for _, ix := range t.Indexes {
			post = append(post, fmt.Sprintf("CREATE INDEX %s ON %s (%s);",
				quoteDQ(indexName(t, ix)), quoteDQ(t.Name), quotedCols(ix, quoteDQ)))
		}
		if l := pkLine(t, quoteDQ); l != "" {
			lines = append(lines, l)
		}
		for _, c := range refCols(t) {
			rt, rp, ok := fkTargetMap(byID, c)
			if !ok {
				continue
			}
			lines = append(lines, fmt.Sprintf(
				"  CONSTRAINT %s FOREIGN KEY (%s) REFERENCES %s (%s) ON DELETE %s%s",
				quoteDQ("fk_"+t.Name+"_"+c.Name), quoteDQ(c.Name), quoteDQ(rt.Name), quoteDQ(rp.Name), fkAction(c), fkUpdateClause(c)))
		}
		out = append(out, "CREATE TABLE "+quoteDQ(t.Name)+" (\n"+strings.Join(lines, ",\n")+"\n);")
		out = append(out, post...)
	}
	return strings.Join(out, "\n") + "\n"
}

// ---- SQLite ----

func sqliteColType(c Col, portable bool) (string, string) {
	base, args := splitType(c.Type)
	ty, check := base, ""
	switch base {
	case "ENUM":
		ty = "TEXT"
		if sql, ok := enumCheck(c.Name, c.Type, quoteTick); ok {
			check = sql
		}
	case "BOOLEAN":
		if portable {
			ty = "INTEGER"
		}
	case "DATETIME", "TIMESTAMP":
		if portable {
			ty = "TEXT"
		}
	}
	if args != "" && ty == base {
		ty = base + "(" + args + ")"
	}
	return ty, check
}

func sqliteColDef(c Col, ty, check string, aiPk bool) string {
	var s string
	if aiPk && c.Pk {
		s = quoteTick(c.Name) + " INTEGER PRIMARY KEY"
	} else {
		s = quoteTick(c.Name) + " " + ty
		if c.Nn || c.Pk {
			s += " NOT NULL"
		}
		if c.Ux {
			s += " UNIQUE"
		}
		if check != "" {
			s += " " + check
		}
	}
	if c.Comment != "" {
		s = "  -- " + c.Name + ": " + c.Comment + "\n  " + s
	} else {
		s = "  " + s
	}
	return s
}

// buildSqlite emits SQLite DDL. typesMode selects how BOOLEAN/DATETIME/
// TIMESTAMP render — see SqliteTypesNative / SqliteTypesPortable for what each
// buys and what the portable one costs. ENUM is TEXT + CHECK either way.
//
// The mode is recorded in the header comment when it is not the default, so a
// portable file reopens as portable. Without that the setting would be lost on
// reopen: the dropdown would read "native" while the bytes on disk were written
// as portable, and a newly added BOOLEAN column would contradict the file's own
// convention. The native header stays exactly as it was, so files already
// written keep their bytes.
//
// ponytail: SQLite lacks COMMENT and ENUM; comments become -- lines, ENUM becomes
// TEXT + inline CHECK, AUTO_INCREMENT relies on the INTEGER PRIMARY KEY rowid alias.
func buildSqlite(tables []Table, typesMode string) string {
	header := "-- Generated by erd-creator (SQLite)"
	portable := typesMode == SqliteTypesPortable
	if portable {
		header = "-- Generated by erd-creator (SQLite, types: " + SqliteTypesPortable + ")"
	}
	byID := tableMap(tables)
	out := []string{header}
	for _, t := range tables {
		if len(t.Columns) == 0 {
			continue
		}
		var lines, post []string
		pks := pkCols(t)
		// rowid alias: single integer PK → inline INTEGER PRIMARY KEY, auto-assign for free
		aiPk := len(pks) == 1 && pks[0].Ai && isInt(baseOf(pks[0].Type))
		for _, c := range t.Columns {
			ty, check := sqliteColType(c, portable)
			lines = append(lines, sqliteColDef(c, ty, check, aiPk))
			if c.Ix {
				post = append(post, fmt.Sprintf("CREATE INDEX IF NOT EXISTS %s ON %s (%s);",
					quoteTick("idx_"+t.Name+"_"+c.Name), quoteTick(t.Name), quoteTick(c.Name)))
			}
		}
		// Composite indexes: separate statements after the table, like the
		// single-column ones above.
		for _, ix := range t.Indexes {
			post = append(post, fmt.Sprintf("CREATE INDEX IF NOT EXISTS %s ON %s (%s);",
				quoteTick(indexName(t, ix)), quoteTick(t.Name), quotedCols(ix, quoteTick)))
		}
		if !aiPk {
			if l := pkLine(t, quoteTick); l != "" {
				lines = append(lines, l)
			}
		}
		for _, c := range refCols(t) {
			rt, rp, ok := fkTargetMap(byID, c)
			if !ok {
				continue
			}
			lines = append(lines, fmt.Sprintf(
				"  FOREIGN KEY (%s) REFERENCES %s (%s) ON DELETE %s%s",
				quoteTick(c.Name), quoteTick(rt.Name), quoteTick(rp.Name), fkAction(c), fkUpdateClause(c)))
		}
		out = append(out, "CREATE TABLE "+quoteTick(t.Name)+" (\n"+strings.Join(lines, ",\n")+"\n);")
		out = append(out, post...)
	}
	return strings.Join(out, "\n") + "\n"
}
