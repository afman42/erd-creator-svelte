// attachPendingFKs drops an FK whose CHILD column is gone (valid parent table,
// ghost child): the refactored guard split table-missing from column-missing,
// and only the table half had a pin. The drop must warn "unknown column".
func TestAttachPendingFKUnknownColumnWarns(t *testing.T) {
	s := &Schema{Tables: []Table{
		{ID: "t1", Name: "users", Columns: []Col{{Name: "id", Type: "INT", Pk: true}}},
		{ID: "t2", Name: "posts", Columns: []Col{{Name: "user_id", Type: "INT"}}},
	}}
	byName := map[string]int{"users": 0}
	byID := map[string]int{"t1": 0, "t2": 1}
	var reasons []string
	attachPendingFKs(s, byName, byID,
		[]pendingFK{{tableID: "t2", col: "ghost", table: "users", action: "CASCADE"}},
		func(p pendingFK, reason string) { reasons = append(reasons, reason) })
	if s.Tables[1].Columns[0].Ref != nil {
		t.Error("FK on a ghost child column must be dropped")
	}
	if len(reasons) != 1 || reasons[0] != "unknown column" {
		t.Fatalf("drop reason = %v, want [unknown column]", reasons)
	}
	if w := fkDropWarning(pendingFK{col: "ghost"}, "unknown column"); !strings.Contains(w, "unknown column") {
		t.Errorf("warning does not name the cause: %q", w)
	}
	// default branch: an unexpected reason still renders, never empty
	if w := fkDropWarning(pendingFK{col: "c"}, "bogus"); !strings.Contains(w, "dropped") {
		t.Errorf("default warning renders nothing useful: %q", w)
	}
}

// lintFK strips the postgres [] suffix before comparing: an INT[] FK onto an
// INT PK is a match, not a mismatch. The strip was added with the lintFK
// extraction and had no direct pin; the negative control keeps it honest.
func TestLintArraySuffixNoMismatch(t *testing.T) {
	match := &Schema{Tables: []Table{
		{ID: "t1", Name: "p", Columns: []Col{{Name: "id", Type: "INT", Pk: true}}},
		{ID: "t2", Name: "c", Columns: []Col{{Name: "tags", Type: "INT[]", Ref: &Ref{TableID: "t1"}}}},
	}}
	if l := match.Lint(); len(l) != 0 {
		t.Errorf("INT[] FK onto INT PK flagged: %v", l)
	}
	mismatch := &Schema{Tables: []Table{
		{ID: "t1", Name: "p", Columns: []Col{{Name: "id", Type: "INT", Pk: true}}},
		{ID: "t2", Name: "c", Columns: []Col{{Name: "v", Type: "VARCHAR(9)", Ref: &Ref{TableID: "t1"}}}},
	}}
	if l := mismatch.Lint(); len(l) == 0 {
		t.Error("VARCHAR FK onto INT PK no longer flagged")
	}
}

// saveFile's validateDialectForSave branch: an unknown non-empty dialect is
// refused with the shared prefix before anything reaches disk (export's
// unknown-dialect 400 is pinned in main_test.go; the save half was not).
func TestSaveUnknownDialectRejected(t *testing.T) {
	dir := t.TempDir()
	h := handleFiles(dir)
	body, _ := json.Marshal(&Schema{Dialect: "oracle", Tables: []Table{
		{ID: "t1", Name: "t", Columns: []Col{{Name: "id", Type: "INT"}}},
	}})
	rec := do(t, h, "PUT", "/api/files/a.sql", strings.NewReader(string(body)))
	if rec.Code != http.StatusBadRequest {
		t.Fatalf("code %d, want 400 (%s)", rec.Code, rec.Body.String())
	}
	if !strings.HasPrefix(rec.Body.String(), "invalid schema: ") {
		t.Errorf("body lacks the shared prefix: %q", rec.Body.String())
	}
	if !strings.Contains(rec.Body.String(), "oracle") {
		t.Errorf("body should name the dialect: %q", rec.Body.String())
	}
	if _, err := os.Stat(filepath.Join(dir, "a.sql")); err == nil {
		t.Error("rejected save left a file behind")
	}
}
