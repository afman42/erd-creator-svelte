// ---- 1. markPKColumns: a composite PK naming a ghost column errors
// identically across all grammars ----
//
// TestGhostPKUXIXRejectedAllDialects pins single-column ghost clauses; the
// shared markPKColumns loop also serves multi-column PKs, and the three
// strict parsers must report the same text (same line, same quoting of the
// name) so a file refused by one grammar is refused the same way by all.
func TestGhostCompositePKIdenticalAcrossDialects(t *testing.T) {
	fixtures := map[string]string{
		DialectMysql: "-- Generated by erd-creator\n" +
			"CREATE TABLE `a` (\n  `id` INT,\n  PRIMARY KEY (`id`, `ghost`)\n) ENGINE=InnoDB;\n",
		DialectMariaDB: "-- Generated by erd-creator (MariaDB)\n" +
			"CREATE TABLE `a` (\n  `id` INT,\n  PRIMARY KEY (`id`, `ghost`)\n) ENGINE=InnoDB;\n",
		DialectPostgres: "-- Generated by erd-creator (PostgreSQL)\n" +
			"CREATE TABLE \"a\" (\n  \"id\" INT,\n  PRIMARY KEY (\"id\", \"ghost\")\n);\n",
		DialectSqlite: "-- Generated by erd-creator (SQLite)\n" +
			"CREATE TABLE `a` (\n  `id` INT,\n  PRIMARY KEY (`id`, `ghost`)\n);\n",
	}
	var want string
	for _, dialect := range []string{DialectMysql, DialectMariaDB, DialectPostgres, DialectSqlite} {
		_, err := ParseDDL(fixtures[dialect])
		if err == nil {
			t.Fatalf("%s: composite PK over ghost column accepted", dialect)
		}
		if want == "" {
			want = err.Error()
			if !strings.Contains(want, `unknown column "ghost"`) {
				t.Fatalf("first error does not name the ghost column: %q", want)
			}
			continue
		}
		if err.Error() != want {
			t.Errorf("%s error %q differs from %q", dialect, err.Error(), want)
		}
	}
}

// ---- 2. internalFail: 500 responses never echo filesystem paths ----
//
// The helper's contract is that format/args go to the log only and the body
// is the bare msg. Pinned directly, plus through the two store paths whose
// failures reach it without an existing pin (save temp creation, copy read).
func TestInternalFailNeverEchoesPath(t *testing.T) {
	rec := httptest.NewRecorder()
	internalFail(rec, "save failed", "save temp %s: %v", "/etc/secret/store", errors.New("boom"))
	if rec.Code != http.StatusInternalServerError {
		t.Fatalf("code %d, want 500", rec.Code)
	}
	if body := rec.Body.String(); body != "save failed\n" {
		t.Errorf("body %q, want exactly the msg", body)
	}
	if strings.Contains(rec.Body.String(), "/etc/secret") {
		t.Errorf("path leaked into 500 body: %q", rec.Body.String())
	}
}

// A store dir that is a FILE, not a directory: the schema validates and the
// DDL generates, so save reaches createTemp, which fails (not a directory).
// User-visible: 500 "save failed" with no path.
func TestSaveTempFailureIs500WithoutPath(t *testing.T) {
	dir := t.TempDir()
	notADir := filepath.Join(dir, "notadir")
	if err := os.WriteFile(notADir, []byte("x"), 0o644); err != nil {
		t.Fatal(err)
	}
	h := handleFiles(notADir)
	rec := do(t, h, "PUT", "/api/files/a.sql", jsonBody(sampleSchema()))
	if rec.Code != http.StatusInternalServerError {
		t.Fatalf("code %d, want 500 (%s)", rec.Code, rec.Body.String())
	}
	if !strings.Contains(rec.Body.String(), "save failed") {
		t.Errorf("body should say 'save failed': %q", rec.Body.String())
	}
	if strings.Contains(rec.Body.String(), "notadir") {
		t.Errorf("path leaked into 500 body: %q", rec.Body.String())
	}
}

// A source named *.sql that is a DIRECTORY: stat passes, the open succeeds,
// and the read fails (EISDIR), reaching copyFile's internalFail branch.
// User-visible: 500 "copy failed" with no path, and no target left behind.
func TestCopyReadFailureIs500WithoutPath(t *testing.T) {
	dir := t.TempDir()
	if err := os.Mkdir(filepath.Join(dir, "a.sql"), 0o755); err != nil {
		t.Fatal(err)
	}
	h := handleFiles(dir)
	rec := do(t, h, "POST", "/api/files/copy", jsonBody(map[string]string{"from": "a.sql", "to": "b.sql"}))
	if rec.Code != http.StatusInternalServerError {
		t.Fatalf("code %d, want 500 (%s)", rec.Code, rec.Body.String())
	}
	if !strings.Contains(rec.Body.String(), "copy failed") {
		t.Errorf("body should say 'copy failed': %q", rec.Body.String())
	}
	if strings.Contains(rec.Body.String(), dir) {
		t.Errorf("path leaked into 500 body: %q", rec.Body.String())
	}
	if _, err := os.Stat(filepath.Join(dir, "b.sql")); err == nil {
		t.Error("failed copy left a target behind")
	}
}

// ---- 3. failValidation/failBadJSON: shared prefixes on every 400 ----
//
// The refactors unified every schema/JSON rejection onto two helpers; the pin
// is the prefix on each reachable path, so a future inline http.Error with a
// different wording fails here.
func TestFailPrefixesUnified(t *testing.T) {
	badSchema := func() []byte {
		b, err := json.Marshal(Schema{Tables: []Table{{ID: "t1", Name: "bad\x01", Columns: []Col{}}}})
		if err != nil {
			t.Fatalf("marshal: %v", err)
		}
		return b
	}

	// invalid schema → "invalid schema: " on lint, inserts, export, save
	lintRec := do(t, http.HandlerFunc(handleSchemaAPI), "POST", "/api/lint", strings.NewReader(string(badSchema())))
	if lintRec.Code != http.StatusBadRequest || !strings.HasPrefix(lintRec.Body.String(), "invalid schema: ") {
		t.Errorf("lint invalid schema: %d %q", lintRec.Code, lintRec.Body.String())
	}
	insRec := do(t, http.HandlerFunc(handleSchemaAPI), "POST", "/api/inserts", strings.NewReader(string(badSchema())))
	if insRec.Code != http.StatusBadRequest || !strings.HasPrefix(insRec.Body.String(), "invalid schema: ") {
		t.Errorf("inserts invalid schema: %d %q", insRec.Code, insRec.Body.String())
	}
	expRec := do(t, http.HandlerFunc(handleExport), "POST", "/export", strings.NewReader(
		`{"dialect":"mysql","schema":{"tables":[{"id":"t1","name":"t","columns":[{"name":"a","type":"VARCHAR(1;DROP)"}]}]}}`))
	if expRec.Code != http.StatusBadRequest || !strings.HasPrefix(expRec.Body.String(), "invalid schema: ") {
		t.Errorf("export invalid schema: %d %q", expRec.Code, expRec.Body.String())
	}
	saveRec := do(t, handleFiles(t.TempDir()), "PUT", "/api/files/a.sql", strings.NewReader(string(badSchema())))
	if saveRec.Code != http.StatusBadRequest || !strings.HasPrefix(saveRec.Body.String(), "invalid schema: ") {
		t.Errorf("save invalid schema: %d %q", saveRec.Code, saveRec.Body.String())
	}

	// bad JSON → "bad json: " on lint, export, save, rename, copy
	for name, rec := range map[string]*httptest.ResponseRecorder{
		"lint":   do(t, http.HandlerFunc(handleSchemaAPI), "POST", "/api/lint", strings.NewReader(`{oops`)),
		"export": do(t, http.HandlerFunc(handleExport), "POST", "/export", strings.NewReader(`{oops`)),
		"save":   do(t, handleFiles(t.TempDir()), "PUT", "/api/files/a.sql", strings.NewReader(`{oops`)),
		"rename": do(t, handleFiles(t.TempDir()), "POST", "/api/files/rename", strings.NewReader(`{oops`)),
		"copy":   do(t, handleFiles(t.TempDir()), "POST", "/api/files/copy", strings.NewReader(`{oops`)),
	} {
		if rec.Code != http.StatusBadRequest || !strings.HasPrefix(rec.Body.String(), "bad json: ") {
			t.Errorf("%s bad json: %d %q", name, rec.Code, rec.Body.String())
		}
	}
}

// ---- 4. statCapped: boundary + error passthrough (the 413s themselves are
// pinned by TestSizeCapOpenAndCopy; this pins the helper both callers share)
func TestStatCappedBoundary(t *testing.T) {
	dir := t.TempDir()
	at := filepath.Join(dir, "at.sql")
	if err := os.WriteFile(at, make([]byte, maxOpenFile), 0o644); err != nil {
		t.Fatal(err)
	}
	if tooLarge, err := statCapped(at); err != nil || tooLarge {
		t.Errorf("exactly maxOpenFile: tooLarge=%v err=%v, want false/nil", tooLarge, err)
	}
	over := filepath.Join(dir, "over.sql")
	if err := os.WriteFile(over, make([]byte, maxOpenFile+1), 0o644); err != nil {
		t.Fatal(err)
	}
	if tooLarge, err := statCapped(over); err != nil || !tooLarge {
		t.Errorf("maxOpenFile+1: tooLarge=%v err=%v, want true/nil", tooLarge, err)
	}
	if _, err := statCapped(filepath.Join(dir, "gone.sql")); err == nil {
		t.Error("missing file should return the stat error for the caller to map")
	}
}

