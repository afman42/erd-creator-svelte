// AI + DEFAULT is invalid DDL in every dialect (MySQL refuses a DEFAULT on
// AUTO_INCREMENT, Postgres on an identity column, SQLite on the rowid alias),
// so the pair is refused up front rather than emitted for the database to
// reject. A hand-written file carrying the pair must fail on open too.
func TestRejectsAiWithDefault(t *testing.T) {
	s := &Schema{Tables: []Table{{Name: "t", Columns: []Col{
		{Name: "id", Type: "INT", Ai: true, Nn: true, Pk: true, Default: "0"},
	}}}}
	if err := s.Validate(); err == nil {
		t.Error("accepted an AUTO_INCREMENT column with a DEFAULT")
	}
	// the file path: emitted by hand, opened through ParseDDL, rejected
	handWritten := "-- Generated by erd-creator\nCREATE TABLE `t` (\n  `id` INT NOT NULL AUTO_INCREMENT DEFAULT 0 PRIMARY KEY\n);\n"
	if _, err := ParseDDL(handWritten); err == nil {
		t.Error("ParseDDL accepted an AUTO_INCREMENT column with a DEFAULT")
	}
}

func TestTableCommentRoundTrip(t *testing.T) {
	for _, d := range []string{"mysql", "mariadb", "postgres"} {
		s := defaultsSample()
		s.Dialect = d
		sql, err := s.GenSQL()
		if err != nil {
			t.Fatalf("%s GenSQL: %v", d, err)
		}
		g, err := ParseDDL(sql)
		if err != nil {
			t.Fatalf("%s parse: %v\n%s", d, err, sql)
		}
		if g.Tables[0].Comment != "the users table" {
			t.Errorf("%s: table comment %q, want %q", d, g.Tables[0].Comment, "the users table")
		}
		if g.Tables[1].Comment != "" {
			t.Errorf("%s: comment-less table gained %q", d, g.Tables[1].Comment)
		}
	}
}

// SQLite has no table comment, so buildSqlite omits it. The omission is
// deliberate and documented (lossy, like TINYINT on postgres): assert it so
// nobody "fixes" it by emitting a -- line the parser cannot read back.
func TestTableCommentDroppedForSqlite(t *testing.T) {
	sql, err := exportSQL("sqlite", defaultsSample().Tables)
	if err != nil {
		t.Fatal(err)
	}
	if strings.Contains(sql, "COMMENT") {
		t.Errorf("sqlite emitted a table comment it cannot parse back:\n%s", sql)
	}
	g, err := ParseDDL(sql)
	if err != nil {
		t.Fatal(err)
	}
	if g.Tables[0].Comment != "" {
		t.Errorf("sqlite reopen gained comment %q", g.Tables[0].Comment)
	}
}

