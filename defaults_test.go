// defaultsSample exercises every DEFAULT shape the emitters must carry:
// a quoted string, a bare keyword/function, a numeric literal, and an
// expression wrapped in parens. The table carries a comment too, so the
// table-comment round-trip is pinned in the same place.
func defaultsSample() *Schema {
	users := Table{ID: "t1", Name: "users", Comment: "the users table", Columns: []Col{
		{Name: "id", Type: "INT", Pk: true, Nn: true, Ai: true},
		{Name: "status", Type: "VARCHAR(20)", Nn: true, Default: "'active'"},
		{Name: "created_at", Type: "DATETIME", Default: "CURRENT_TIMESTAMP"},
		{Name: "score", Type: "INT", Default: "0"},
		{Name: "token", Type: "VARCHAR(64)", Default: "(uuid())"},
	}}
	logs := Table{ID: "t2", Name: "logs", Columns: []Col{
		{Name: "msg", Type: "TEXT", Default: "'it''s fine'"},
	}}
	return &Schema{Tables: []Table{users, logs}}
}

func TestDefaultEmitAllDialects(t *testing.T) {
	cases := []struct{ dialect, want string }{
		{"mysql", "DEFAULT 'active'"},
		{"mysql", "DEFAULT CURRENT_TIMESTAMP"},
		{"mysql", "DEFAULT 0"},
		{"mysql", "DEFAULT (uuid())"},
		{"mariadb", "DEFAULT 'active'"},
		{"postgres", "DEFAULT 'active'"},
		{"postgres", "DEFAULT CURRENT_TIMESTAMP"},
		{"postgres", "DEFAULT (uuid())"},
		{"sqlite", "DEFAULT 'active'"},
		{"sqlite", "DEFAULT CURRENT_TIMESTAMP"},
		{"sqlite", "DEFAULT (uuid())"},
	}
	for _, c := range cases {
		sql, err := exportSQL(c.dialect, defaultsSample().Tables)
		if err != nil {
			t.Fatalf("%s: %v", c.dialect, err)
		}
		if !strings.Contains(sql, c.want) {
			t.Errorf("%s output missing %q:\n%s", c.dialect, c.want, sql)
		}
	}
}

func TestDefaultRoundTripEachDialect(t *testing.T) {
	for _, d := range []string{"mysql", "mariadb", "postgres", "sqlite"} {
		s := defaultsSample()
		s.Dialect = d
		sql, err := s.GenSQL()
		if err != nil {
			t.Fatalf("%s GenSQL: %v", d, err)
		}
		g, err := ParseDDL(sql)
		if err != nil {
			t.Fatalf("%s parse: %v\n%s", d, err, sql)
		}
		cols := g.Tables[0].Columns
		want := map[string]string{
			"status":     "'active'",
			"created_at": "CURRENT_TIMESTAMP",
			"score":      "0",
			"token":      "(uuid())",
		}
		for name, wantDefault := range want {
			var got string
			for _, c := range cols {
				if c.Name == name {
					got = c.Default
				}
			}
			if got != wantDefault {
				t.Errorf("%s: column %s default %q, want %q", d, name, got, wantDefault)
			}
		}
		// the escaped quote survives the string literal round-trip
		if g.Tables[1].Columns[0].Default != "'it''s fine'" {
			t.Errorf("%s: escaped-quote default %q lost", d, g.Tables[1].Columns[0].Default)
		}
	}
}

// An empty default emits no clause: files written before the field existed,
// and schemas that never set one, keep their exact bytes. The golden tests
// pin the full output; this pins the per-column shape.
func TestDefaultEmptyOmitsClause(t *testing.T) {
	for _, d := range []string{"mysql", "postgres", "sqlite"} {
		sql, err := exportSQL(d, sample()) // sample() (export_test.go) has no defaults
		if err != nil {
			t.Fatalf("%s: %v", d, err)
		}
		if hasDefaultClause(sql) {
			t.Errorf("%s emitted a DEFAULT for a schema with none:\n%s", d, sql)
		}
	}
}

// hasDefaultClause reports whether emitted DDL contains a DEFAULT clause.
// Postgres's identity rendering ("GENERATED BY DEFAULT AS IDENTITY") contains
// the word DEFAULT without being a column DEFAULT, so it is stripped first.
func hasDefaultClause(sql string) bool {
	cleaned := strings.ReplaceAll(sql, "GENERATED BY DEFAULT AS IDENTITY", "")
	return strings.Contains(cleaned, "DEFAULT")
}

func TestRejectsDefaultInjection(t *testing.T) {
	bad := []string{
		"0; DROP TABLE users;--",
		"'x'; DROP TABLE users;--",
		"5 -- trailing comment",
		"CURRENT_TIMESTAMP; ",
		`0" OR "1"="1`, // double-quote injection shape
		"0` OR 1=1",    // backtick injection shape
		"0 /* block comment */",
		"(0", // unbalanced parens
		"0)", // unbalanced parens
		"'unterminated",
	}
	for _, v := range bad {
		s := &Schema{Tables: []Table{{Name: "t", Columns: []Col{{Name: "c", Type: "INT", Default: v}}}}}
		if err := s.Validate(); err == nil {
			t.Errorf("accepted unsafe default %q", v)
		}
	}
	good := []string{
		"0", "-1", "1.5", ".5", "'a'", "''", "NULL", "TRUE", "FALSE",
		"CURRENT_TIMESTAMP", "CURRENT_TIMESTAMP(6)", "NOW()", "(uuid())",
		"'it''s'", "'a;b'", "CURRENT_TIMESTAMP + INTERVAL '1 day'",
	}
	for _, v := range good {
		s := &Schema{Tables: []Table{{Name: "t", Columns: []Col{{Name: "c", Type: "INT", Default: v}}}}}
		if err := s.Validate(); err != nil {
			t.Errorf("rejected legitimate default %q: %v", v, err)
		}
	}
}

// The validateOutput last gate is quote-aware: a `;` INSIDE a quoted default
// literal must emit cleanly (it is part of the value), while one outside would
// be the injection shape. Pin the full emit path (GenSQL runs validateOutput),
// not just Validate.
func TestDefaultQuotedSemicolonEmitsSafely(t *testing.T) {
	for _, d := range []string{"mysql", "postgres", "sqlite"} {
		s := &Schema{Dialect: d, Tables: []Table{{Name: "t", Columns: []Col{
			{Name: "c", Type: "INT", Default: "'a;b'"},
		}}}}
		sql, err := s.GenSQL()
		if err != nil {
			t.Fatalf("%s: GenSQL rejected a quoted-semicolon default: %v\n%s", d, err, sql)
		}
		if !strings.Contains(sql, "DEFAULT 'a;b'") {
			t.Errorf("%s: quoted-semicolon default not emitted:\n%s", d, sql)
		}
	}
}

// ENUM shares the mysql column line with DEFAULT (type args + DEFAULT clause):
// pin that the parser keeps both.
func TestDefaultEnumMysql(t *testing.T) {
	s := &Schema{Dialect: DialectMysql, Tables: []Table{{Name: "t", Columns: []Col{
		{Name: "status", Type: "ENUM('a','b')", Default: "'a'"},
	}}}}
	sql, err := s.GenSQL()
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(sql, "DEFAULT 'a'") {
		t.Fatalf("missing DEFAULT:\n%s", sql)
	}
	g, err := ParseDDL(sql)
	if err != nil {
		t.Fatal(err)
	}
	c := g.Tables[0].Columns[0]
	if c.Default != "'a'" || c.Type != "ENUM('a','b')" {
		t.Errorf("mysql ENUM+default round-trip: type %q default %q", c.Type, c.Default)
	}
}

// A PK that is not AI may carry a DEFAULT (MySQL allows it) — the AI+DEFAULT
// refusal is about auto-increment, not primary keys.
func TestDefaultOnPrimaryKey(t *testing.T) {
	s := &Schema{Dialect: DialectMysql, Tables: []Table{{Name: "t", Columns: []Col{
		{Name: "id", Type: "INT", Pk: true, Nn: true, Default: "0"},
	}}}}
	sql, err := s.GenSQL()
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(sql, "DEFAULT 0") {
		t.Fatalf("missing DEFAULT on PK:\n%s", sql)
	}
	g, err := ParseDDL(sql)
	if err != nil {
		t.Fatal(err)
	}
	if c := g.Tables[0].Columns[0]; c.Default != "0" || !c.Pk {
		t.Errorf("PK+default round-trip: default %q pk %v", c.Default, c.Pk)
	}
}

